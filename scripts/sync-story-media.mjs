import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const storyRoot = path.join(root, "public", "images", "childhood", "story");
const musicRoot = path.join(root, "public", "music", "story");
const outputPath = path.join(root, "src", "data", "storyMedia.generated.ts");

const IMAGE_EXTENSIONS = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".webp",
  ".gif",
  ".avif",
]);

// Read slugs from storyMemories.ts by parsing slug fields
const storyMemoriesSource = fs.readFileSync(
  path.join(root, "src", "data", "storyMemories.ts"),
  "utf8"
);
const slugMatches = [...storyMemoriesSource.matchAll(/slug:\s*"([^"]+)"/g)];
const orderedSlugs = slugMatches.map((match) => match[1]);

function naturalSort(a, b) {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
}

let cacheVersion = 0;
const storyImages = {};
const storySongs = {};

function cacheBustedPublicUrl(publicPath, fullPath) {
  const mtime = fs.statSync(fullPath).mtimeMs;
  cacheVersion = Math.max(cacheVersion, mtime);
  return `${publicPath}?v=${Math.floor(mtime)}`;
}

for (const slug of orderedSlugs) {
  const folder = path.join(storyRoot, slug);

  if (!fs.existsSync(folder)) {
    console.warn(`[sync-story-media] Missing folder: ${folder}`);
    storyImages[slug] = [];
    continue;
  }

  const files = fs
    .readdirSync(folder)
    .filter((file) => IMAGE_EXTENSIONS.has(path.extname(file).toLowerCase()))
    .sort(naturalSort);

  storyImages[slug] = files.map((file) => {
    const fullPath = path.join(folder, file);
    const publicPath = `/images/childhood/story/${slug}/${file}`;
    return cacheBustedPublicUrl(publicPath, fullPath);
  });

  const songPath = path.join(musicRoot, slug, "song.mp3");
  if (fs.existsSync(songPath)) {
    storySongs[slug] = cacheBustedPublicUrl(
      `/music/story/${slug}/song.mp3`,
      songPath
    );
  } else {
    console.warn(`[sync-story-media] Missing song: ${songPath}`);
    storySongs[slug] = `/music/story/${slug}/song.mp3`;
  }

  console.log(
    `[sync-story-media] ${slug}: ${storyImages[slug].length} image(s), song: ${fs.existsSync(songPath) ? "ok" : "missing"}`
  );
}

const fileContents = `// Auto-generated by scripts/sync-story-media.mjs — do not edit manually.
// Re-run: npm run sync:media (also runs automatically before dev/build)

export const STORY_MEDIA_CACHE_VERSION = ${Math.floor(cacheVersion)};

export const storyImagesBySlug: Record<string, string[]> = ${JSON.stringify(storyImages, null, 2)};

export const storySongsBySlug: Record<string, string> = ${JSON.stringify(storySongs, null, 2)};
`;

fs.writeFileSync(outputPath, fileContents, "utf8");
console.log(`[sync-story-media] Wrote ${outputPath}`);
